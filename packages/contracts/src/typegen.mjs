/** Convert JSON Schema catalog to TypeScript SDK contracts at build time.
 * Generated declarations are checked in so normal code completion works even
 * on development hosts where npm registry access is blocked.
 */
import {schemas,operations} from './catalog.mjs';
function ts(schema,indent=0){
 if(!schema)return 'unknown';
 if(schema.$ref)return schema.$ref.split('/').at(-1);
 // R1-04: nullable score/result unions must not collapse to 'unknown' in SDK.
 if(Array.isArray(schema.anyOf))return schema.anyOf.map(x=>ts(x,indent)).join(' | ');
 if(Array.isArray(schema.oneOf))return schema.oneOf.map(x=>ts(x,indent)).join(' | ');
 if(schema.enum)return schema.enum.map(v=>JSON.stringify(v)).join(' | ');
 if(Array.isArray(schema.type))return schema.type.map(t=>ts({...schema,type:t},indent)).join(' | ');
 if(schema.type==='string')return 'string';
 if(schema.type==='integer'||schema.type==='number')return 'number';
 if(schema.type==='boolean')return 'boolean';
 if(schema.type==='null')return 'null';
 if(schema.type==='array')return `Array<${ts(schema.items,indent)}>`;
 if(schema.type==='object'){
   const entries=Object.entries(schema.properties??{});
   if(!entries.length)return 'Record<string, unknown>';
   const pad=' '.repeat(indent+2),required=new Set(schema.required??[]);
   return `{\n${entries.map(([key,v])=>`${pad}${key}${required.has(key)?'':'?'}: ${ts(v,indent+2)};`).join('\n')}\n${' '.repeat(indent)}}`;
 }
 return 'unknown';
}
export function generateTypes(){
 const lines=['/** GENERATED by tools/generate-api.mjs — do not edit manually. */'];
 for(const [name,schema] of Object.entries(schemas))lines.push(`export type ${name} = ${ts(schema)};`);
 lines.push(`export interface OperationMap {`);
 for(const op of operations){
  const paths=[...op.path.matchAll(/:([a-zA-Z][a-zA-Z0-9_]*)/g)].map(x=>x[1]);
  const args=[];
  for(const name of paths)args.push(`${name}: string`);
  if(op.query)args.push(`query?: ${ts({type:'object',properties:op.query})}`);
  if(op.body)args.push(`body: ${ts(op.body)}`);
  lines.push(`  ${op.id}: { args: ${args.length?`{ ${args.join('; ')} }`:'Record<string, never>'}; result: ${ts(op.response)}; };`);
 }
 lines.push('}');
 lines.push('export type OperationId = keyof OperationMap;');
 lines.push('export type OperationArgs<K extends OperationId> = OperationMap[K]["args"];');
 lines.push('export type OperationResult<K extends OperationId> = OperationMap[K]["result"];');
 return lines.join('\n')+'\n';
}
